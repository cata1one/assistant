"""Распознавание запросов по ключевым словам в обычных сообщениях.

«новые слова сегодня», «дз», «конспект», «тест», «мой словарь» — короткие
запросы к ассистенту. Объявления преподавателя вида «Новые слова сегодня:
apple, pear» запросом не считаются: в них после двоеточия идёт список.
"""

from __future__ import annotations

import re

from .textnorm import for_matching

COMMANDS: list[tuple[str, re.Pattern[str]]] = [
    ("words_today", re.compile(
        r"^(?:покажи|выведи|дай|какие|напомни|список|перечисли)?\s*(?:мне\s+)?(?:все\s+)?(?:новые\s+)?слова\s+(?:за\s+|на\s+)?сегодня"
        r"(?:\s+(?:были|было|выучили|учили))?$"
        r"|^(?:новые\s+)?слова\s+(?:за\s+)?(?:сегодняшн\w*\s+)?(?:день|дня)$|^сегодняшние\s+слова$"
        r"|^какие\s+(?:новые\s+)?слова\s+(?:мы\s+)?(?:сегодня\s+)?(?:выучили|учили|прошли|были)(?:\s+сегодня)?$"
        r"|^(?:new\s+)?words\s+(?:for\s+)?today$|^today'?s\s+words$")),
    ("words_lesson", re.compile(
        r"^(?:покажи\s+|какие\s+|напомни\s+|перечисли\s+)?(?:новые\s+)?слова(?:\s+(?:с|за|прошлого|последнего|этого)\s+урока"
        r"|\s+урока)?$|^новые\s+слова$|^словарь\s+урока$|^new\s+words$|^vocabulary$")),
    ("words_all", re.compile(r"^(?:мой|весь|мои|все|покажи)\s+(?:мой\s+|весь\s+)?(?:словарь|слова)$|^словарь$|^все\s+слова$"
                             r"|^my\s+(?:words|vocabulary)$")),
    ("homework", re.compile(
        r"^(?:какое\s+|покажи\s+|мое\s+|напомни\s+|а\s+)?(?:домашнее\s+задание|домашнее|домашка|домашку|дз|д/з|homework)"
        r"(?:\s+(?:на\s+)?(?:сегодня|завтра|урока|к\s+следующему\s+уроку))?$|^что\s+(?:нам\s+|мне\s+)?(?:задали|задано)"
        r"(?:\s+на\s+дом)?$")),
    ("test", re.compile(r"^(?:дай\s+|хочу\s+|пройти\s+|покажи\s+|начать\s+)?(?:тест|проверь\s+меня|проверка\s+знаний|quiz|test)"
                        r"(?:\s+по\s+(?:уроку|словам))?$")),
    ("answers", re.compile(r"^(?:покажи\s+)?(?:ответы|ключ|ключ\s+к\s+тесту|ответы\s+(?:к|на)\s+тест\w*)$")),
    ("summary", re.compile(r"^(?:покажи\s+|дай\s+)?(?:конспект|итоги|итог|резюме|summary)(?:\s+(?:урока|занятия))?$"
                           r"|^что\s+(?:мы\s+)?(?:прошли|проходили|изучали|изучили)(?:\s+(?:на\s+уроке|сегодня))?$")),
    ("report", re.compile(r"^(?:отчет|отчёт|полный\s+отчет)(?:\s+(?:по\s+)?урок\w*)?$")),
    ("help", re.compile(r"^(?:помощь|команды|help|что\s+ты\s+умеешь|как\s+пользоваться|меню)$")),
]

MAX_WORDS = 8


def detect_command(text: str) -> str | None:
    """Вернёт имя команды или None. Срабатывает только на короткие запросы целиком."""
    raw = (text or "").strip()
    if not raw or len(raw.split()) > MAX_WORDS:
        return None
    if re.search(r"[:\-—–]\s*\S", raw) and not raw.startswith("/"):
        return None  # «новые слова сегодня: …» — это объявление списка, а не запрос
    norm = for_matching(raw.lstrip("/"))
    norm = re.sub(r"[?!.,…]+", " ", norm)
    norm = re.sub(r"\s+", " ", norm).strip()
    norm = re.sub(r"^(?:ассистент|бот|помощник|пожалуйста)\s*,?\s*", "", norm)
    norm = re.sub(r"\s*(?:пожалуйста|плиз|please)$", "", norm)
    for name, rx in COMMANDS:
        if rx.search(norm):
            return name
    return None


